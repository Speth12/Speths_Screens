// Generates the per-widget-type settings types from schema.json, which
// quicktype merges into one flat type: packages/shared-types/src/widgets.ts
// and internal/project/widgets.go. Run by `npm run gen:types`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(readFileSync(resolve(root, "schema.json"), "utf8"));
const defs = schema.$defs;
const refName = (ref) => ref.replace("#/$defs/", "");

// Each widget type, its settings definition, and that definition's
// properties: frame settings (allOf) first, then its own.
const types = defs.TypedProps.oneOf.map((branch) => {
  const type = branch.properties.type.const;
  const name = refName(branch.properties.props.$ref);
  const props = [];
  const collect = (defName) => {
    const def = defs[defName];
    for (const a of def.allOf ?? []) collect(refName(a.$ref));
    for (const [key, node] of Object.entries(def.properties ?? {})) props.push({ key, node });
  };
  collect(name);
  return { type, name, props };
});
if (types.length !== defs.WidgetType.enum.length) throw new Error("TypedProps does not cover every WidgetType");

const header = "Generated by scripts/gen-widget-types.mjs from schema.json. DO NOT EDIT.";
const refs = new Set();

// ── TypeScript ─────────────────────────────────────────────────────────────

function tsType(node) {
  if (node.$ref) { const n = refName(node.$ref); refs.add(n); return n; }
  if (node.type === "string") return "string";
  if (node.type === "number" || node.type === "integer") return "number";
  if (node.type === "boolean") return "boolean";
  if (node.type === "array") return `${tsType(node.items)}[]`;
  if (node.type === "object" && node.additionalProperties) return `Record<string, ${tsType(node.additionalProperties)}>`;
  if (!node.type) return "unknown";
  throw new Error(`no TypeScript type for ${JSON.stringify(node)}`);
}
const doc = (node, indent) => (node.description ? `${indent}/** ${node.description} */\n` : "");

let ts = `// ${header}\n// One settings type per widget type; quicktype's Widget has them merged.\n`;
const tsBody = [];
const frame = Object.entries(defs.FrameProps.properties);
tsBody.push(`/** Settings of the frame every widget is drawn in; every settings type includes them. */\nexport interface FrameProps {\n${frame.map(([key, node]) => `${doc(node, "  ")}  ${key}?: ${tsType(node)};`).join("\n")}\n}\n`);
for (const t of types) {
  tsBody.push(`/** Settings of a ${t.type} widget. */\nexport interface ${t.name} {\n${t.props.map((p) => `${doc(p.node, "  ")}  ${p.key}?: ${tsType(p.node)};`).join("\n")}\n}\n`);
}
tsBody.push(`/** Each widget type's settings type. */\nexport interface PropsByType {\n${types.map((t) => `  ${t.type}: ${t.name};`).join("\n")}\n}\n`);
tsBody.push(`/** A widget whose props are typed for its type. */
export type TypedWidget<T extends WidgetType = WidgetType> = {
  [K in T]: Omit<Widget, "type" | "props"> & { type: K; props?: PropsByType[K] };
}[T];
`);
tsBody.push(`
/** Each widget type's settings, frame settings first. */
export const PROPS_KEYS: { readonly [K in WidgetType]: readonly (keyof PropsByType[K] & string)[] } = {
${types.map((t) => `  ${t.type}: [${t.props.map((p) => JSON.stringify(p.key)).join(", ")}],`).join("\n")}
};

/** A widget as the typed widget of its type. The props are not checked:
 *  use it on projects that passed validation. */
export function typed<T extends WidgetType>(w: Widget & { type: T }): TypedWidget<T> {
  return w as unknown as TypedWidget<T>;
}
`);
ts += `import type { ${[...refs, "Widget", "WidgetType"].sort().join(", ")} } from "./project";\n\n` + tsBody.join("\n") ;
writeFileSync(resolve(root, "packages/shared-types/src/widgets.ts"), ts);

// ── Go ─────────────────────────────────────────────────────────────────────

const goField = (key) => {
  let f = key[0].toUpperCase() + key.slice(1);
  f = f.replace(/Id$/, "ID").replace(/Url$/, "URL");
  return f;
};
function goType(node) {
  if (node.$ref) return refName(node.$ref);
  if (node.type === "string") return "string";
  if (node.type === "number") return "float64";
  if (node.type === "integer") return "int64";
  if (node.type === "boolean") return "bool";
  if (node.type === "array") return `[]${goType(node.items)}`;
  if (node.type === "object" && node.additionalProperties) return `map[string]${goType(node.additionalProperties)}`;
  if (!node.type) return "interface{}";
  throw new Error(`no Go type for ${JSON.stringify(node)}`);
}
const goPtr = (node) => {
  const t = goType(node);
  return t.startsWith("[]") || t.startsWith("map[") || t === "interface{}" ? t : `*${t}`;
};
const typeConst = (type) => {
  // quicktype's constant names for WidgetType values (internal/project/types.go).
  const goTypes = readFileSync(resolve(root, "internal/project/types.go"), "utf8");
  const m = goTypes.match(new RegExp(`\\n\\t(\\w+)\\s+WidgetType = "${type}"`));
  if (!m) throw new Error(`no WidgetType constant for ${type}`);
  return m[1];
};

let go = `// Code generated by scripts/gen-widget-types.mjs from schema.json. DO NOT EDIT.\n\npackage project\n\n`;
for (const t of types) {
  go += `// ${t.name} holds the settings of a ${t.type} widget.\ntype ${t.name} struct {\n`;
  for (const p of t.props) {
    if (p.node.description) go += `\t// ${p.node.description}\n`;
    go += `\t${goField(p.key)} ${goPtr(p.node)} \`json:"${p.key},omitempty"\`\n`;
  }
  go += `}\n\n`;
}
for (const t of types) {
  const fn = `As${t.type[0].toUpperCase()}${t.type.slice(1)}`;
  go += `// ${fn} returns w's settings as a ${t.type} widget's. It fails when w is\n// another type or has a setting a ${t.type} does not have.\nfunc (w Widget) ${fn}() (${t.name}, error) {\n\tvar p ${t.name}\n\treturn p, decodeProps(w.Type, ${typeConst(t.type)}, w.Props, &p)\n}\n\n`;
}
go += `// PropsKeys lists each widget type's settings, frame settings first.\nvar PropsKeys = map[WidgetType][]string{\n`;
for (const t of types) go += `\t${typeConst(t.type)}: {${t.props.map((p) => JSON.stringify(p.key)).join(", ")}},\n`;
go += `}\n`;
writeFileSync(resolve(root, "internal/project/widgets.go"), go);
console.log(`generated settings types for ${types.length} widget types`);
